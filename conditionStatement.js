// if condition example
let number = 5
if(number>10){
    console.log("number is greater than 10")
}

// if else example
let age=30
if(age>=18){
    console.log("eligible to vote")
}
else{
    console.log("not eligible to vote")
}

//switch example
let day=2
switch(day) // inside bracket value is called expression 
{
case 1:
    console.log("Monday")
    break;
case 2:
    console.log("tuesday")
    break;
case 3:
    console.log("wednesday")
    break;
default:
    console.log("Invalid input")
}
